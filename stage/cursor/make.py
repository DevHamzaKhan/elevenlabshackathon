"""Generate the three cursor designs as SVG + Android VectorDrawable from one source.

Run: uv run stage/cursor/make.py
Writes <name>.svg, cursor_<name>.xml for each design, and cursor.xml (the recommended one).
Every design: 48 x 48 viewport, the touch hotspot is the exact centre (24, 24).
Only paths are used (circles become two arcs) so the XML is valid VectorDrawable.
"""

from pathlib import Path
from xml.etree import ElementTree as ET

HERE = Path(__file__).parent
RECOMMENDED = "ring"

ACCENT = "#7C5CFF"  # Bobby violet
ACCENT_DARK = "#4B2FD6"
WHITE = "#FFFFFF"
BLACK = "#000000"
INK = "#1B1640"


def circle(cx: float, cy: float, r: float) -> str:
    """A full circle as path data: two half arcs."""
    return (
        f"M{cx - r:g},{cy:g} "
        f"A{r:g},{r:g} 0 1,1 {cx + r:g},{cy:g} "
        f"A{r:g},{r:g} 0 1,1 {cx - r:g},{cy:g} Z"
    )


def p(d, fill=None, fill_alpha=1.0, stroke=None, stroke_width=0.0, stroke_alpha=1.0, cap=None, join=None):
    return dict(d=d, fill=fill, fill_alpha=fill_alpha, stroke=stroke, stroke_width=stroke_width,
                stroke_alpha=stroke_alpha, cap=cap, join=join)


# Each design is a list of paths, drawn bottom to top.
DESIGNS = {
    # Target ring: open centre so the label being tapped stays readable; dot marks the exact touch point.
    "ring": [
        p(circle(24, 25, 15), stroke=BLACK, stroke_width=6.5, stroke_alpha=0.22),  # soft shadow
        p(circle(24, 24, 15), fill=ACCENT, fill_alpha=0.14),                          # faint tint inside
        p(circle(24, 24, 15), stroke=WHITE, stroke_width=5.5),                        # white outline
        p(circle(24, 24, 15), stroke=ACCENT, stroke_width=3),                         # accent ring
        p(circle(24, 24.6, 3.6), fill=BLACK, fill_alpha=0.25),                        # dot shadow
        p(circle(24, 24, 3.4), fill=WHITE),
        p(circle(24, 24, 2.1), fill=ACCENT_DARK),
    ],
    # Soft glowing dot: like a fingertip with a halo.
    "glow": [
        p(circle(24, 24, 21), fill=ACCENT, fill_alpha=0.10),
        p(circle(24, 24, 17), fill=ACCENT, fill_alpha=0.16),
        p(circle(24, 24, 13.5), fill=ACCENT, fill_alpha=0.24),
        p(circle(24, 25.2, 9.6), fill=BLACK, fill_alpha=0.30),
        p(circle(24, 24, 9.2), fill=WHITE),
        p(circle(24, 24, 6.8), fill=ACCENT),
        p(circle(24, 24, 1.7), fill=WHITE),
    ],
    # Friendly "Bobby" mark: a rounded teardrop whose sharp tip is the hotspot, with a little face.
    "bobby": [
        p("M25.2,25.6 H34.2 A9,9 0 0 1 43.2,34.6 A9,9 0 0 1 34.2,43.6 A9,9 0 0 1 25.2,34.6 Z",
          fill=BLACK, fill_alpha=0.28),                                                # shadow
        p("M24,24 H33 A9,9 0 0 1 42,33 A9,9 0 0 1 33,42 A9,9 0 0 1 24,33 Z",
          fill=ACCENT, stroke=WHITE, stroke_width=2.4, join="round"),
        p(circle(30.6, 31.4, 1.45), fill=WHITE),                                      # eyes
        p(circle(35.6, 31.4, 1.45), fill=WHITE),
        p("M29.6,35.4 Q33.1,38.6 36.6,35.4", stroke=WHITE, stroke_width=1.6, cap="round"),  # smile
        p(circle(24, 24, 1.3), fill=WHITE),                                           # tip marker
        p(circle(24, 24, 0.7), fill=INK),
    ],
}


def to_svg(name: str, paths: list[dict]) -> str:
    lines = [
        '<svg xmlns="http://www.w3.org/2000/svg" width="48" height="48" viewBox="0 0 48 48">',
        f"  <!-- Bobby cursor '{name}'. Hotspot (touch point) = exact centre (24,24). Generated by make.py. -->",
    ]
    for q in paths:
        a = [f'd="{q["d"]}"']
        a.append(f'fill="{q["fill"]}"' if q["fill"] else 'fill="none"')
        if q["fill"] and q["fill_alpha"] != 1:
            a.append(f'fill-opacity="{q["fill_alpha"]:g}"')
        if q["stroke"]:
            a.append(f'stroke="{q["stroke"]}" stroke-width="{q["stroke_width"]:g}"')
            if q["stroke_alpha"] != 1:
                a.append(f'stroke-opacity="{q["stroke_alpha"]:g}"')
            if q["cap"]:
                a.append(f'stroke-linecap="{q["cap"]}"')
            if q["join"]:
                a.append(f'stroke-linejoin="{q["join"]}"')
        lines.append(f"  <path {' '.join(a)}/>")
    lines.append("</svg>")
    return "\n".join(lines) + "\n"


def argb(hex_rgb: str) -> str:
    return "#FF" + hex_rgb.lstrip("#").upper()


def to_vector(name: str, paths: list[dict]) -> str:
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        f"<!-- Bobby cursor '{name}'. 48dp, 48x48 viewport, hotspot = exact centre (24,24).",
        "     Generated by stage/cursor/make.py; edit there, not here. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="48dp"',
        '    android:height="48dp"',
        '    android:viewportWidth="48"',
        '    android:viewportHeight="48">',
    ]
    for q in paths:
        a = [f'android:pathData="{q["d"]}"']
        if q["fill"]:
            a.append(f'android:fillColor="{argb(q["fill"])}"')
            if q["fill_alpha"] != 1:
                a.append(f'android:fillAlpha="{q["fill_alpha"]:g}"')
        if q["stroke"]:
            a.append(f'android:strokeColor="{argb(q["stroke"])}"')
            a.append(f'android:strokeWidth="{q["stroke_width"]:g}"')
            if q["stroke_alpha"] != 1:
                a.append(f'android:strokeAlpha="{q["stroke_alpha"]:g}"')
            if q["cap"]:
                a.append(f'android:strokeLineCap="{q["cap"]}"')
            if q["join"]:
                a.append(f'android:strokeLineJoin="{q["join"]}"')
        lines.append("    <path\n        " + "\n        ".join(a) + " />")
    lines.append("</vector>")
    return "\n".join(lines) + "\n"


def main() -> None:
    for name, paths in DESIGNS.items():
        (HERE / f"{name}.svg").write_text(to_svg(name, paths))
        xml = to_vector(name, paths)
        ET.fromstring(xml.split("?>", 1)[1])  # must parse
        (HERE / f"cursor_{name}.xml").write_text(xml)
    (HERE / "cursor.xml").write_text((HERE / f"cursor_{RECOMMENDED}.xml").read_text())
    print("wrote", ", ".join(DESIGNS), "; cursor.xml =", RECOMMENDED)


if __name__ == "__main__":
    main()
