// Bundles every stage/hints/*.md (except TO-CHECK.md) into generated/hints.ts at build time.
// Runs on npm install, npm start, npm run prebuild and in check.sh. Missing folder = no hints.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const hintsDir = path.resolve(here, '../../stage/hints');
const out = path.resolve(here, '../generated/hints.ts');

let files = [];
try {
  files = fs
    .readdirSync(hintsDir)
    .filter((f) => f.endsWith('.md') && f.toUpperCase() !== 'TO-CHECK.MD')
    .sort();
} catch {
  // no stage/hints yet
}
const hints = files.map((f) => fs.readFileSync(path.join(hintsDir, f), 'utf8'));
const body =
  '// Generated by tools/gen-hints.mjs from stage/hints/*.md. Do not edit.\n' +
  `export const hintFiles: string[] = ${JSON.stringify(files)};\n` +
  `export const hints: string[] = ${JSON.stringify(hints, null, 2)};\n`;
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, body);
console.log(`hints: bundled ${files.length} file(s): ${files.join(', ') || '(none)'}`);
