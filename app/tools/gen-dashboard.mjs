// Bundles stage/dashboard/index.html into generated/dashboard.ts so the app can show the live
// dashboard in a WebView. The chosen cursor (stage/cursor/CHOSEN) is inlined as a data URI because
// the page's relative ../cursor/ path doesn't exist inside the app. Runs with gen-hints.
// Missing stage/dashboard = empty string, and the app hides its Dashboard button.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const stage = path.resolve(here, '../../stage');
const out = path.resolve(here, '../generated/dashboard.ts');

let html = '';
try {
  html = fs.readFileSync(path.join(stage, 'dashboard/index.html'), 'utf8');
  let name = 'ring';
  try { name = fs.readFileSync(path.join(stage, 'cursor/CHOSEN'), 'utf8').trim().split(/\s+/)[0] || name; } catch {}
  const svgPath = path.join(stage, 'cursor', name, `${name}.svg`);
  if (fs.existsSync(svgPath)) {
    const uri = 'data:image/svg+xml;base64,' + fs.readFileSync(svgPath).toString('base64');
    html = html.replace(/src="\.\.\/cursor\/[^"]+\.svg"/, `src="${uri}"`);
  }
} catch {
  // no stage/dashboard yet
}
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out,
  '// Generated by tools/gen-dashboard.mjs from stage/dashboard/index.html. Do not edit.\n' +
  `export const dashboardHtml: string = ${JSON.stringify(html)};\n`);
console.log(`dashboard: bundled ${html ? (html.length / 1024).toFixed(0) + ' KB' : '(none)'}`);
